using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;
using TNRD.Zeepkist.Tester.Scenarios;
using TNRD.Zeepkist.Tester.Sdk;

namespace TNRD.Zeepkist.Tester.Cli;

/// <summary>
/// The step reference: every step and state of a registry as Markdown, grouped by namespace.
/// </summary>
internal static class StepReference
{
    public static string Write(StepRegistry registry)
    {
        var markdown = new StringBuilder();
        markdown.Append("# Step reference\n\nGenerated by `ztest docs` from the steps' code, so don't edit it by hand.\n\n");
        markdown.Append("## Steps\n\n");
        WriteByNamespace(markdown, registry.Steps, step => step.Namespace, step => step.Name, step => WriteStep(markdown, step));

        if (registry.States.Count > 0)
        {
            markdown.Append("## States\n\n");
            WriteByNamespace(markdown, registry.States, state => state.Namespace, state => state.Name, state => WriteState(markdown, state, registry));
        }

        return markdown.ToString().TrimEnd('\n') + "\n";
    }

    /// <summary>
    /// The tester's own first, then each mod's by name.
    /// </summary>
    private static void WriteByNamespace<T>(StringBuilder markdown, IEnumerable<T> items, Func<T, string> namespaceOf, Func<T, string> name, Action<T> write)
    {
        foreach (var group in items.GroupBy(namespaceOf).OrderBy(group => group.Key, StringComparer.Ordinal))
        {
            markdown.Append($"### {(group.Key.Length == 0 ? "Tester" : $"`{group.Key}`")}\n\n");
            foreach (var item in group.OrderBy(name, StringComparer.Ordinal))
                write(item);
        }
    }

    private static void WriteState(StringBuilder markdown, StateDescriptor state, StepRegistry registry)
    {
        var steps = registry.Steps;
        var outerStates = OuterStates(state, registry.States);
        WriteHeading(markdown, "state", state.FullName, state.Documentation);

        var enteredBy = StepLinks(steps.Where(step => step.Enters.Contains(state.FullName)));
        var leftBy = StepLinks(steps.Where(step => step.Leaves.Any(outerStates.Contains)));
        WriteList(markdown, [
            state.Within == null ? null : $"Within {StateLink(state.Within)}",
            state.Hint == null ? null : $"Hint: {state.Hint}",
            enteredBy.Length == 0 ? null : $"Entered by {enteredBy}",
            leftBy.Length == 0 ? null : $"Left by {leftBy}",
        ]);
    }

    /// <summary>
    /// The entry's heading, with an anchor that links elsewhere in the reference point at, and its summary.
    /// </summary>
    private static void WriteHeading(StringBuilder markdown, string kind, string fullName, string documentation)
    {
        markdown.Append($"#### <a id=\"{kind}-{fullName}\"></a>`{fullName}`\n\n");
        if (documentation != null)
            markdown.Append($"{documentation}\n\n");
    }

    /// <summary>
    /// The state and those it's within, which leaving any of also leaves it.
    /// </summary>
    private static HashSet<string> OuterStates(StateDescriptor state, IReadOnlyList<StateDescriptor> states)
    {
        var outer = new HashSet<string>();
        for (var current = state; current != null && outer.Add(current.FullName);)
            current = states.FirstOrDefault(other => other.FullName == current.Within);

        return outer;
    }

    private static string StepLinks(IEnumerable<StepDescriptor> steps)
    {
        return string.Join(", ", steps.Select(step => step.FullName).Order(StringComparer.Ordinal).Select(name => $"[`{name}`](#step-{name})"));
    }

    private static void WriteList(StringBuilder markdown, IEnumerable<string> lines)
    {
        var written = lines.Where(line => line != null).ToList();
        if (written.Count == 0)
            return;

        foreach (var line in written)
            markdown.Append($"- {line}\n");

        markdown.Append('\n');
    }

    private static void WriteStep(StringBuilder markdown, StepDescriptor step)
    {
        WriteHeading(markdown, "step", step.FullName, step.Documentation);

        if (step.Arguments.Count > 0)
        {
            markdown.Append("| Argument | Type | Required | Default | Description |\n");
            markdown.Append("| --- | --- | --- | --- | --- |\n");
            WriteArguments(markdown, step.Arguments, string.Empty);
            markdown.Append('\n');
        }

        WriteList(markdown, [
            step.Requires.Count == 0 ? null : $"Needs {string.Join(", and ", step.Requires.Select(alternatives => string.Join(" or ", alternatives.Select(StateLink))))}",
            step.Enters.Count == 0 ? null : $"Enters {StateLinks(step.Enters)}",
            step.Leaves.Count == 0 ? null : $"Leaves {StateLinks(step.Leaves)}",
        ]);

        if (step.Examples.Count > 0)
            markdown.Append($"```yaml\n{string.Join("\n", step.Examples)}\n```\n\n");
    }

    private static string StateLinks(IEnumerable<string> states)
    {
        return string.Join(", ", states.Select(StateLink));
    }

    private static string StateLink(string state)
    {
        return $"[`{state}`](#state-{state})";
    }

    private static void WriteArguments(StringBuilder markdown, IReadOnlyList<ArgumentDescriptor> arguments, string prefix)
    {
        foreach (var argument in arguments)
        {
            var name = $"`{prefix}{argument.Name}`{(argument.IsPrimary ? " (primary)" : string.Empty)}";
            var defaultValue = argument.Default == null ? string.Empty : Code(WrittenValue.DefaultText(argument.Default));
            markdown.Append($"| {name} | {Cell(ArgumentText(argument))} | {(argument.IsRequired ? "yes" : "no")} | {Cell(defaultValue)} | {Cell(argument.Documentation ?? string.Empty)} |\n");

            var (nested, depth) = ObjectInside(argument.Type);
            if (nested != null)
                WriteArguments(markdown, nested.Arguments, $"{prefix}{argument.Name}{string.Concat(Enumerable.Repeat("[]", depth))}.");
        }
    }

    /// <summary>
    /// The object an argument holds, through however many lists, whose arguments a scenario writes under it.
    /// </summary>
    private static (ArgumentType Object, int ListDepth) ObjectInside(ArgumentType type)
    {
        var depth = 0;
        for (; type.Kind == ArgumentKind.List; depth++)
            type = type.ItemType;

        return (type.Kind == ArgumentKind.Object ? type : null, depth);
    }

    private static string ArgumentText(ArgumentDescriptor argument)
    {
        var text = TypeText(argument.Type);
        if (argument.Minimum != null && argument.Maximum != null)
            text += $", from {Number(argument.Minimum.Value)} to {Number(argument.Maximum.Value)}";
        else if (argument.Minimum != null)
            text += $", at least {Number(argument.Minimum.Value)}";
        else if (argument.Maximum != null)
            text += $", at most {Number(argument.Maximum.Value)}";

        // Every value of a type like keys has its pattern, which says less than the type's name
        if (argument.Pattern != null && argument.Pattern != argument.Type.Pattern)
            text += $" matching {Code(argument.Pattern)}";

        if (argument.MinItems != null)
            text += $", at least {argument.MinItems.Value}";

        return text;
    }

    private static string TypeText(ArgumentType type)
    {
        return type.Kind switch
        {
            ArgumentKind.TextBlock => "text-block",
            ArgumentKind.FileName => "file-name",
            ArgumentKind.Enum => $"one of {string.Join(", ", type.EnumValues.Select(Code))}",
            ArgumentKind.Name => $"a name for a new `{type.ValueKind}`",
            ArgumentKind.Ref => $"a `{type.ValueKind}`'s name",
            ArgumentKind.List => type.ItemType.Kind == ArgumentKind.Enum ? $"list, each {TypeText(type.ItemType)}" : $"list of {ItemsText(type.ItemType)}",
            _ => type.Kind.ToString().ToLowerInvariant(),
        };
    }

    private static string ItemsText(ArgumentType itemType)
    {
        return itemType.Kind switch
        {
            ArgumentKind.Object => "objects",
            ArgumentKind.List => $"lists of {ItemsText(itemType.ItemType)}",
            _ => TypeText(itemType),
        };
    }

    private static string Number(double value)
    {
        return value.ToString(CultureInfo.InvariantCulture);
    }

    /// <summary>
    /// A code span, fenced with more backticks than the text has in a row.
    /// </summary>
    private static string Code(string text)
    {
        if (!text.Contains('`'))
            return $"`{text}`";

        // A space keeps a backtick at either end from joining the fence, and Markdown drops it again
        var fence = new string('`', LongestRun(text, '`') + 1);
        var pad = text.StartsWith('`') || text.EndsWith('`') ? " " : string.Empty;
        return $"{fence}{pad}{text}{pad}{fence}";
    }

    private static int LongestRun(string text, char character)
    {
        int longest = 0, current = 0;
        foreach (var each in text)
        {
            current = each == character ? current + 1 : 0;
            longest = Math.Max(longest, current);
        }

        return longest;
    }

    /// <summary>
    /// A table cell can't hold a pipe or a line break.
    /// </summary>
    private static string Cell(string text)
    {
        return text.Replace("|", "\\|").Replace("\r\n", " ").Replace('\r', ' ').Replace('\n', ' ');
    }
}
