using System.Collections.Generic;
using System.IO;
using System.Runtime.CompilerServices;
using TNRD.Zeepkist.Tester.Cli;
using TNRD.Zeepkist.Tester.Sdk;
using TNRD.Zeepkist.Tester.Tests.SampleCore;
using TNRD.Zeepkist.Tester.Tests.SampleMod;
using Xunit;

namespace TNRD.Zeepkist.Tester.Tests;

public class StepReferenceTests
{
    /// <summary>
    /// On a difference, the new reference is next to the snapshot as <c>.received.md</c>: check it and copy it over.
    /// </summary>
    [Fact]
    public void TheSampleMod_MatchesTheSnapshot()
    {
        var snapshot = Path.Combine(SourceFolder(), "Snapshots", "step-reference.md");
        var received = Path.ChangeExtension(snapshot, ".received.md");
        var markdown = StepReference.Write(OfflineRegistry.Read([typeof(Compile).Assembly.Location], typeof(CoreStep).Assembly.Location));

        var expected = File.Exists(snapshot) ? File.ReadAllText(snapshot).ReplaceLineEndings("\n") : null;
        if (markdown == expected)
        {
            File.Delete(received);
            return;
        }

        File.WriteAllText(received, markdown);
        Assert.Fail($"The step reference isn't the snapshot. Compare {received} with {snapshot}.");
    }

    [Fact]
    public void TheReference_SaysItsGenerated()
    {
        Assert.StartsWith("# Step reference\n\nGenerated by `ztest docs` from the steps' code, so don't edit it by hand.\n\n## Steps\n", Write([]));
    }

    [Fact]
    public void AStep_HasItsNameAndSummary_UnderItsNamespace()
    {
        var markdown = Write([Step("wait", documentation: "Waits a while.")]);

        Assert.Contains("## Steps\n\n### Tester\n\n#### <a id=\"step-wait\"></a>`wait`\n\nWaits a while.\n", markdown);
    }

    [Fact]
    public void AStepsArguments_AreATable_OfTheirTypeWhetherRequiredDefaultAndSummary()
    {
        var markdown = Write([Step("wait", arguments: [
            new ArgumentDescriptor { Name = "seconds", PropertyName = "Seconds", Type = Type(ArgumentKind.Seconds), IsPrimary = true, IsRequired = true, Documentation = "How long." },
            new ArgumentDescriptor { Name = "quiet", PropertyName = "Quiet", Type = Type(ArgumentKind.Bool), Default = false },
        ])]);

        Assert.Contains(
            "| Argument | Type | Required | Default | Description |\n"
            + "| --- | --- | --- | --- | --- |\n"
            + "| `seconds` (primary) | seconds | yes |  | How long. |\n"
            + "| `quiet` | bool | no | `false` |  |\n",
            markdown);
    }

    [Theory]
    [MemberData(nameof(Types))]
    public void AnArgumentsTypeColumn_SaysWhatValuesFit(ArgumentDescriptor argument, string expected)
    {
        var markdown = Write([Step("step", arguments: [argument])]);

        Assert.Contains($"| `a` | {expected} | no |", markdown);
    }

    public static TheoryData<ArgumentDescriptor, string> Types()
    {
        return new TheoryData<ArgumentDescriptor, string>
        {
            { Argument(new ArgumentType { Kind = ArgumentKind.Enum, EnumValues = ["left", "right"] }), "one of `left`, `right`" },
            { Argument(Type(ArgumentKind.Int), minimum: 1, maximum: 8), "int, from 1 to 8" },
            { Argument(Type(ArgumentKind.Float), minimum: 0.5), "float, at least 0.5" },
            { Argument(Type(ArgumentKind.String), pattern: "^[a|b]+$"), "string matching `^[a\\|b]+$`" },
            { Argument(new ArgumentType { Kind = ArgumentKind.List, ItemType = Type(ArgumentKind.Seconds) }, minItems: 1), "list of seconds, at least 1" },
            { Argument(new ArgumentType { Kind = ArgumentKind.Name, ValueKind = "block" }), "a name for a new `block`" },
            { Argument(new ArgumentType { Kind = ArgumentKind.Ref, ValueKind = "block" }), "a `block`'s name" },
            { Argument(new ArgumentType { Kind = ArgumentKind.Enum, EnumValues = ["a`b"] }), "one of ``a`b``" },
            { Argument(new ArgumentType { Kind = ArgumentKind.List, ItemType = new ArgumentType { Kind = ArgumentKind.Enum, EnumValues = ["left", "right"] } }), "list, each one of `left`, `right`" },
            { Argument(new ArgumentType { Kind = ArgumentKind.Keys, Pattern = "^long$" }, pattern: "^long$"), "keys" },
            { Argument(Type(ArgumentKind.String), pattern: "^`+$"), "string matching ``^`+$``" },
        };
    }

    [Fact]
    public void AnObjectsArguments_FollowItsRow_UnderItsName()
    {
        var item = new ArgumentType { Kind = ArgumentKind.Object, Arguments = [Argument(Type(ArgumentKind.Int))] };
        var markdown = Write([Step("step", arguments: [
            new ArgumentDescriptor { Name = "item", PropertyName = "Item", Type = item, Documentation = "The item." },
            new ArgumentDescriptor { Name = "items", PropertyName = "Items", Type = new ArgumentType { Kind = ArgumentKind.List, ItemType = item } },
        ])]);

        Assert.Contains(
            "| `item` | object | no |  | The item. |\n"
            + "| `item.a` | int | no |  |  |\n"
            + "| `items` | list of objects | no |  |  |\n"
            + "| `items[].a` | int | no |  |  |\n",
            markdown);
    }

    [Fact]
    public void AStepsStates_LinkToThem()
    {
        var markdown = Write([new StepDescriptor
        {
            Name = "swap",
            Namespace = "mod",
            Arguments = [],
            Requires = [["editor"], ["mod.a", "mod.b"]],
            Enters = ["mod.a"],
            Leaves = ["editor"],
        }]);

        Assert.Contains(
            "- Needs [`editor`](#state-editor), and [`mod.a`](#state-mod.a) or [`mod.b`](#state-mod.b)\n"
            + "- Enters [`mod.a`](#state-mod.a)\n"
            + "- Leaves [`editor`](#state-editor)\n",
            markdown);
    }

    [Fact]
    public void AStepsExamples_AreYaml()
    {
        var markdown = Write([new StepDescriptor { Name = "wait", Namespace = string.Empty, Arguments = [], Examples = ["- wait: 2", "- wait: { seconds: 2 }"] }]);

        Assert.Contains("```yaml\n- wait: 2\n- wait: { seconds: 2 }\n```\n", markdown);
    }

    [Fact]
    public void AState_SaysWhatItsWithin_HowToGetIntoIt_AndTheStepsThatEnterAndLeaveIt()
    {
        var markdown = Write(
            [
                new StepDescriptor { Name = "open", Namespace = "mod", Arguments = [], Enters = ["mod.open"] },
                new StepDescriptor { Name = "reopen", Namespace = "mod", Arguments = [], Enters = ["mod.open"] },
                new StepDescriptor { Name = "close", Namespace = "mod", Arguments = [], Leaves = ["mod.open"] },
            ],
            [new StateDescriptor { Name = "open", Namespace = "mod", Within = "editor", Hint = "Add `mod.open` first.", Documentation = "The window is open." }]);

        Assert.Contains(
            "## States\n\n### `mod`\n\n#### <a id=\"state-mod.open\"></a>`mod.open`\n\n"
            + "The window is open.\n\n"
            + "- Within [`editor`](#state-editor)\n"
            + "- Hint: Add `mod.open` first.\n"
            + "- Entered by [`mod.open`](#step-mod.open), [`mod.reopen`](#step-mod.reopen)\n"
            + "- Left by [`mod.close`](#step-mod.close)\n",
            markdown);
    }

    [Fact]
    public void AStepThatLeavesAState_LeavesTheStatesWithinIt()
    {
        var markdown = Write(
            [new StepDescriptor { Name = "close", Namespace = "mod", Arguments = [], Leaves = ["mod.outer"] }],
            [
                new StateDescriptor { Name = "outer", Namespace = "mod" },
                new StateDescriptor { Name = "middle", Namespace = "mod", Within = "mod.outer" },
                new StateDescriptor { Name = "inner", Namespace = "mod", Within = "mod.middle" },
            ]);

        Assert.Contains("`mod.inner`\n\n- Within [`mod.middle`](#state-mod.middle)\n- Left by [`mod.close`](#step-mod.close)\n", markdown);
    }

    [Fact]
    public void ADefaultWithABacktick_StaysOneCodeSpan()
    {
        var markdown = Write([Step("step", arguments: [new ArgumentDescriptor { Name = "a", PropertyName = "A", Type = Type(ArgumentKind.String), Default = "`x", Documentation = "One\r\nand two." }])]);

        Assert.Contains("| `a` | string | no | `` `x `` | One and two. |", markdown);
    }

    [Fact]
    public void ListsOfListsOfObjects_ShowTheirArguments()
    {
        var item = new ArgumentType { Kind = ArgumentKind.Object, Arguments = [Argument(Type(ArgumentKind.Int))] };
        var rows = new ArgumentType { Kind = ArgumentKind.List, ItemType = new ArgumentType { Kind = ArgumentKind.List, ItemType = item } };
        var markdown = Write([Step("step", arguments: [new ArgumentDescriptor { Name = "grid", PropertyName = "Grid", Type = rows }])]);

        Assert.Contains("| `grid` | list of lists of objects | no |  |  |\n| `grid[][].a` | int | no |  |  |\n", markdown);
    }

    private static string SourceFolder([CallerFilePath] string path = null)
    {
        return Path.GetDirectoryName(path);
    }

    private static string Write(IReadOnlyList<StepDescriptor> steps, IReadOnlyList<StateDescriptor> states = null)
    {
        return StepReference.Write(new StepRegistry { Steps = steps, States = states ?? [] });
    }

    private static StepDescriptor Step(string name, string @namespace = "", string documentation = null, IReadOnlyList<ArgumentDescriptor> arguments = null)
    {
        return new StepDescriptor { Name = name, Namespace = @namespace, Documentation = documentation, Arguments = arguments ?? [] };
    }

    private static ArgumentDescriptor Argument(ArgumentType type, double? minimum = null, double? maximum = null, string pattern = null, int? minItems = null)
    {
        return new ArgumentDescriptor { Name = "a", PropertyName = "A", Type = type, Minimum = minimum, Maximum = maximum, Pattern = pattern, MinItems = minItems };
    }

    private static ArgumentType Type(ArgumentKind kind)
    {
        return new ArgumentType { Kind = kind };
    }
}
